/**
 * levels/*.json：用 tools/fetch-commons.mjs / tools/pixelize.mjs 生成的额外图案，
 * 按文件名排序追加在最后。格式与上面相同，可带 source（素材来源）。
 * 注意：这里必须直接调用 import.meta.glob，不能做 typeof 运行时判断——
 * vite 构建只改写直接调用，包装在条件里会在生产包里静默变空。
 */
const extraModules = import.meta.glob('../../../levels/*.json', { eager: true, import: 'default' }) as Record<string, Pattern & { source?: PatternSource }>;

import { GENERATED_PATTERNS } from './generatedPatterns';

function valid(p: Pattern): boolean {
  return !!p && typeof p.key === 'string' && Array.isArray(p.rows) && p.rows.length > 0 && typeof p.palette === 'object' && p.rows.every((r) => [...r].every((ch) => ch === '.' || ch === ' ' || p.palette[ch]));
}

const generated = GENERATED_PATTERNS.filter((p) => {
  if (valid(p)) return true;
  console.warn('忽略无效的生成图案', p);
  return false;
});

const globbed = Object.keys(extraModules)
  .filter((f) => !f.endsWith('credits.json'))
  .sort()
  .map((f) => extraModules[f])
  .filter((p) => {
    if (valid(p)) return true;
    console.warn('忽略无效的关卡文件', p);
    return false;
  });

export const EXTRA_PATTERNS: (Pattern & { source?: PatternSource })[] = [...generated, ...globbed];

export const PATTERNS: Pattern[] = [...HAND_DRAWN, ...generated, ...globbed.filter((p) => !HAND_DRAWN.some((h) => h.key === p.key) && !generated.some((h) => h.key === p.key))];
